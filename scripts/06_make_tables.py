#!/usr/bin/env python
"""Regenerate every table of the report from the saved result files.

    python scripts/06_make_tables.py

Reads  results/**/summary.json, *_items.csv.gz, downstream.json, train_summary.json,
       results/training_data/stats.json and configs/published.yaml.
Writes results/tables/<name>.md and <name>.csv, plus results/tables/README.md (an index
that also lists the tables that could not be built yet, and why).

No model is run and no GPU is needed. Published numbers and measured numbers are kept
in separate columns or rows, and every published number names its source table.
"""
from __future__ import annotations

import argparse
import os
import sys
import time

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))

from compbind.report import ALL_TABLES, MissingInput, Results, load_published  # noqa: E402
from compbind.utils import ensure_dir, git_commit  # noqa: E402


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    parser.add_argument("--results-dir", default="results")
    parser.add_argument("--published", default=os.path.join("configs", "published.yaml"))
    parser.add_argument("--out-dir", default=None, help="Default: <results-dir>/tables")
    parser.add_argument("--n-boot", type=int, default=2000, help="Bootstrap replicates.")
    args = parser.parse_args()

    results = Results(args.results_dir)
    published = load_published(args.published)
    out_dir = ensure_dir(args.out_dir or os.path.join(args.results_dir, "tables"))
    built, skipped = [], []
    for builder in ALL_TABLES:
        try:
            table = builder(results, published, n_boot=args.n_boot)
        except MissingInput as missing:
            skipped.append((builder.__name__.replace("table_", ""), str(missing)))
            continue
        with open(os.path.join(out_dir, f"{table.name}.md"), "w", encoding="utf-8") as f:
            f.write(table.to_markdown())
        table.frame.to_csv(os.path.join(out_dir, f"{table.name}.csv"), index=False)
        built.append(table)
        print(table.to_markdown())

    lines = ["# Tables", "",
             f"Generated by `scripts/06_make_tables.py` on {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())} "
             f"from the files in `{args.results_dir}/` (code commit `{git_commit() or 'unknown'}`).", ""]
    lines += [f"- [{t.title}]({t.name}.md)" for t in built]
    if skipped:
        lines += ["", "Not built yet:"] + [f"- `{name}`: {reason}" for name, reason in skipped]
    with open(os.path.join(out_dir, "README.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Built {len(built)} tables in {out_dir}" + (f"; skipped {len(skipped)}:" if skipped else ""))
    for name, reason in skipped:
        print(f"  {name}: {reason}")


if __name__ == "__main__":
    main()
